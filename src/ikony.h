// 🧩 Datová struktura pro ikonu
struct IconDef {
    const char* name;
    const unsigned char* bitmap;
    uint8_t width;
    uint8_t height;
};

// 🧠 Seznam všech ikon
const IconDef iconList[] = {
    { "danger24x24", icon_danger24x24, 24, 24 },
    { "wifi16x16", icon_wifi16x16, 16, 16 },
    { "wifi8x7", icon_wifi8x7, 8, 8 },
    { "wifi_cover24x24", icon_wifi_cover24x24, 24, 24 },
    { "wifi_no_signal24x24", icon_wifi_no_signal24x24, 24, 24 },
    { "four_dots_narrow16x5", icon_four_dots_narrow16x5, 16, 5 },
    { "lock_1", icon_lock_1_8x7, 8, 7 },
    { "lock_2", icon_lock_2_8x7, 8, 7 },
    { "water_drop24x24", icon_water_drop24x24, 24, 24 },
    { "water_drop16x16", icon_water_drop16x16, 16, 16 },
};

const uint8_t ICON_COUNT = sizeof(iconList) / sizeof(iconList[0]);

//
// === Funkce pro vykreslení ikony ===
//
void DrawIcon(Adafruit_SSD1306 &display, const char* name, int16_t x, int16_t y) {
    for (uint8_t i = 0; i < ICON_COUNT; i++) {
        if (strcmp(iconList[i].name, name) == 0) {
            display.drawBitmap(x, y, iconList[i].bitmap, iconList[i].width, iconList[i].height, SSD1306_WHITE);
            return;
        }
    }

    // Pokud ikona nenalezena
    display.setTextSize(1);
    display.setTextColor(SSD1306_WHITE);
    display.setCursor(x, y);
    display.print("?");
}
